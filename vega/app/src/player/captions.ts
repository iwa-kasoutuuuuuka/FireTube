import {CaptionTrack, Cue} from '../api/types';

export interface CaptionOption {
  label: string;
  track?: CaptionTrack;
  translateTo?: string;
}

/** 字幕の選択肢: オフ / 各トラック / (日本語が無ければ) 日本語への自動翻訳 */
export function captionOptions(tracks: CaptionTrack[]): CaptionOption[] {
  const options: CaptionOption[] = [{label: 'オフ'}];
  for (const t of tracks) {
    options.push({
      label: t.isAutoGenerated ? `${t.name} (自動生成)` : t.name,
      track: t,
    });
  }
  if (tracks.length > 0 && !tracks.some((t) => t.languageCode === 'ja')) {
    options.push({
      label: '日本語 (自動翻訳)',
      track: tracks[0],
      translateTo: 'ja',
    });
  }
  return options;
}

export function cueAt(cues: Cue[], t: number): string {
  // キューは時刻順。重なるキューは改行でつなぐ
  return cues
    .filter((c) => c.start <= t && t < c.end)
    .map((c) => c.text)
    .join('\n');
}
