jest.mock('@react-native-async-storage/async-storage', () =>
  require('@react-native-async-storage/async-storage/jest/async-storage-mock'),
);

import {
  chooseCaption,
  chooseQuality,
  parseJson3,
  parsePlayerResponse,
  parseVideoRenderers,
} from '../src/api/innertube';
import {CaptionTrack, DashTrack} from '../src/api/types';
import {captionOptions, cueAt} from '../src/player/captions';
import {
  addHistory,
  history,
  positions,
  resumePosition,
  savePosition,
  subscriptions,
  toggleSubscription,
  toggleWatchLater,
  watchLater,
} from '../src/store/library';
import {settings} from '../src/store/settings';

const video = (id: string) => ({
  id,
  title: `t-${id}`,
  uploaderName: 'u',
  thumbnailUrl: '',
  durationSeconds: 100,
});

const track = (
  languageCode: string,
  isAutoGenerated = false,
): CaptionTrack => ({
  baseUrl: `b-${languageCode}${isAutoGenerated ? '-asr' : ''}`,
  languageCode,
  name: languageCode,
  isAutoGenerated,
});

describe('captions', () => {
  it('parses json3 events into cues and skips empty ones', () => {
    const cues = parseJson3({
      events: [
        {
          tStartMs: 1000,
          dDurationMs: 2000,
          segs: [{utf8: 'Hello '}, {utf8: 'world'}],
        },
        {tStartMs: 3000, dDurationMs: 500, segs: [{utf8: '\n'}]},
        {tStartMs: 4000, dDurationMs: 1000, segs: [{utf8: 'Bye'}]},
      ],
    });
    expect(cues).toEqual([
      {start: 1, end: 3, text: 'Hello world'},
      {start: 4, end: 5, text: 'Bye'},
    ]);
    expect(cueAt(cues, 2)).toBe('Hello world');
    expect(cueAt(cues, 3.5)).toBe('');
  });

  it('prefers manual Japanese, else translates the first track', () => {
    expect(
      chooseCaption([track('en'), track('ja', true), track('ja')], 'ja'),
    ).toEqual({
      track: track('ja'),
    });
    expect(chooseCaption([track('en')], 'ja')).toEqual({
      track: track('en'),
      translateTo: 'ja',
    });
    expect(chooseCaption([track('en', true), track('ko')], 'default')).toEqual({
      track: track('ko'),
    });
    expect(chooseCaption([track('en')], 'off')).toBeNull();
  });

  it('offers a Japanese translation option only when there is no Japanese track', () => {
    expect(captionOptions([track('en')]).map((o) => o.label)).toEqual([
      'オフ',
      'en',
      '日本語 (自動翻訳)',
    ]);
    expect(captionOptions([track('ja', true)]).map((o) => o.label)).toEqual([
      'オフ',
      'ja (自動生成)',
    ]);
  });
});

describe('quality', () => {
  const v = (height: number) => ({height} as DashTrack);
  it('chooses the best quality under the limit, or the lowest', () => {
    const list = [v(1080), v(720), v(480)];
    expect(chooseQuality(list, 720)?.height).toBe(720);
    expect(chooseQuality(list, 1080)?.height).toBe(1080);
    expect(chooseQuality(list, 360)?.height).toBe(480);
  });

  it('builds the DASH source within maxHeight and exposes tracks and captions', () => {
    const fmt = (itag: number, mimeType: string, height = 0) => ({
      itag,
      url: `u${itag}`,
      mimeType,
      height,
      bitrate: 1,
      initRange: {start: '0', end: '10'},
      indexRange: {start: '11', end: '20'},
    });
    const info = parsePlayerResponse(
      {
        playabilityStatus: {status: 'OK'},
        streamingData: {
          adaptiveFormats: [
            fmt(137, 'video/mp4; codecs="avc1.640028"', 1080),
            fmt(136, 'video/mp4; codecs="avc1.4D401F"', 720),
            fmt(140, 'audio/mp4; codecs="mp4a.40.2"'),
          ],
        },
        captions: {
          playerCaptionsTracklistRenderer: {
            captionTracks: [
              {
                baseUrl: 'cap',
                languageCode: 'en',
                name: {simpleText: '英語'},
                kind: 'asr',
              },
            ],
          },
        },
        videoDetails: {channelId: 'UCxxxxxxxxxxxxxxxxxxxxxx', author: 'A'},
      },
      'vid',
      'VISIONOS',
      720,
    );
    expect(info.sources[0].label).toBe('DASH 720p');
    expect(info.dashVideos.map((t) => t.height)).toEqual([1080, 720]);
    expect(info.captions).toEqual([
      {baseUrl: 'cap', languageCode: 'en', name: '英語', isAutoGenerated: true},
    ]);
    expect(info.channelId).toBe('UCxxxxxxxxxxxxxxxxxxxxxx');
  });
});

describe('channel id in lists', () => {
  it('reads the owner browseId of a videoRenderer', () => {
    const items = parseVideoRenderers({
      videoRenderer: {
        videoId: 'vid000001',
        title: {simpleText: 'T'},
        ownerText: {
          runs: [
            {
              text: 'Ch',
              navigationEndpoint: {
                browseEndpoint: {browseId: 'UCRIgIJQWuBJ0Cv_VlU3USNA'},
              },
            },
          ],
        },
      },
    });
    expect(items[0].channelId).toBe('UCRIgIJQWuBJ0Cv_VlU3USNA');
  });
});

describe('library', () => {
  beforeEach(() => {
    history.set([]);
    watchLater.set([]);
    subscriptions.set([]);
    positions.set({});
  });

  it('keeps history newest-first without duplicates', () => {
    addHistory(video('a'), 1);
    addHistory(video('b'), 2);
    addHistory(video('a'), 3);
    expect(history.get().map((e) => e.video.id)).toEqual(['a', 'b']);
  });

  it('toggles watch later and subscriptions', () => {
    expect(toggleWatchLater(video('a'))).toBe(true);
    expect(watchLater.get().map((v) => v.id)).toEqual(['a']);
    expect(toggleWatchLater(video('a'))).toBe(false);
    expect(watchLater.get()).toEqual([]);
    expect(toggleSubscription({id: 'UC1', name: 'n'})).toBe(true);
    expect(toggleSubscription({id: 'UC1', name: 'n'})).toBe(false);
    expect(subscriptions.get()).toEqual([]);
  });

  it('saves resume positions but forgets near the start and the end', () => {
    savePosition('a', 5, 100);
    expect(resumePosition('a')).toBe(0);
    savePosition('a', 50, 100);
    expect(resumePosition('a')).toBe(50);
    savePosition('a', 90, 100);
    expect(resumePosition('a')).toBe(0);
  });
});

describe('settings', () => {
  it('normalizes stored values', async () => {
    const AsyncStorage = require('@react-native-async-storage/async-storage');
    await AsyncStorage.setItem(
      'settings',
      JSON.stringify({maxQuality: 999, subtitles: 'ja', sponsorBlock: false}),
    );
    await settings.hydrate();
    expect(settings.get()).toMatchObject({
      maxQuality: 1080,
      subtitles: 'ja',
      sponsorBlock: false,
      resume: true,
    });
  });
});

describe('playback fallback order', () => {
  it('tries a lower DASH quality before HLS', () => {
    const fmt = (itag: number, mimeType: string, height = 0) => ({
      itag,
      url: `u${itag}`,
      mimeType,
      height,
      bitrate: 1,
      initRange: {start: '0', end: '10'},
      indexRange: {start: '11', end: '20'},
    });
    const info = parsePlayerResponse(
      {
        playabilityStatus: {status: 'OK'},
        streamingData: {
          hlsManifestUrl: 'hls',
          adaptiveFormats: [
            fmt(137, 'video/mp4; codecs="avc1.640028"', 1080),
            fmt(135, 'video/mp4; codecs="avc1.4D401E"', 480),
            fmt(140, 'audio/mp4; codecs="mp4a.40.2"'),
          ],
        },
      },
      'vid',
      'VISIONOS',
    );
    expect(info.sources.map((x) => x.label)).toEqual([
      'DASH 1080p',
      'DASH 480p',
      'HLS (自動画質)',
    ]);
  });
});
